// Builds the 4-hourly markdown report from a snapshot.
const DASHBOARD_URL = process.env.DASHBOARD_URL || '';

const px = (sym, x) => (x == null || !Number.isFinite(x) ? '—' : sym === 'SOL' ? x.toFixed(2) : sym === 'ETH' ? x.toFixed(1) : x.toFixed(0));
const sgn = (x, d = 2) => (x >= 0 ? '+' : '') + x.toFixed(d);

export function buildReport(snap, prevSignalIds = new Set()) {
  const t = new Date(snap.generatedAt);
  const stamp = t.toISOString().slice(0, 16).replace('T', ' ') + ' UTC';
  const L = [];
  L.push(`# Crypto trade ideas: ${stamp}`);
  L.push('');
  L.push('## Market snapshot');
  L.push('');
  L.push('| Coin | Price | 24h | Bias (1D / 4H / 1H) | Funding (8h) | OI 24h | Basis |');
  L.push('|---|---|---|---|---|---|---|');
  for (const [sym, S] of Object.entries(snap.symbols)) {
    const tfb = ['1d', '4h', '1h'].map((tf) => S.tf[tf].ta.bias.replace('Strong ', 'Str. ')).join(' / ');
    const F = S.futures;
    L.push(`| ${sym} | ${px(sym, S.price)} | ${sgn(S.change24h)}% | ${tfb} | ${F ? (F.fundingRate * 100).toFixed(4) + '%' : '—'} | ${F?.oiChange24h != null ? sgn(F.oiChange24h * 100, 1) + '%' : '—'} | ${F ? sgn(F.basisPct, 3) + '%' : '—'} |`);
  }
  L.push('');
  const sigs = [...snap.signals].sort((a, b) => b.confidence - a.confidence);
  const fresh = sigs.filter((s) => !prevSignalIds.has(s.id));
  // 1H ideas only make the email at 60%+ confidence; everything stays on the dashboard
  const worthy = (s) => s.tf !== '1h' || s.confidence >= 60;
  const freshShown = fresh.filter(worthy);
  const hidden = fresh.length - freshShown.length;
  const top = (freshShown.length ? freshShown : sigs.filter(worthy)).slice(0, 8);
  L.push(freshShown.length ? `## New trade ideas since the last report (${freshShown.length})` : '## Top live trade ideas (no new high-confidence ones this period)');
  L.push('');
  if (hidden > 0) { L.push(`${hidden} new lower-confidence 1H idea${hidden === 1 ? ' is' : 's are'} on the dashboard's Signals tab.`); L.push(''); }
  if (!top.length) L.push('No live setups right now. Patience is a position.');
  for (const s of top) {
    L.push(`### ${s.symbol} ${s.side.toUpperCase()} · ${s.tf} · ${s.strategyName}: ${s.confidence}% confidence`);
    L.push(`- **Entry** ${px(s.symbol, s.entry)} · **Stop** ${px(s.symbol, s.stop)} (${s.stopPct.toFixed(2)}%) · **TP1** ${px(s.symbol, s.tp1)} (${s.rr1.toFixed(1)}R) · **TP2** ${px(s.symbol, s.tp2)} (${s.rr2.toFixed(1)}R)`);
    L.push(`- Market: ${s.markets.join(' + ')} · Status: ${s.status}${s.backtest?.trades ? ` · Backtest: ${(s.backtest.winRate * 100).toFixed(0)}% win, ${sgn(s.backtest.avgR)}R avg over ${s.backtest.trades} trades` : ''}`);
    L.push(`- Why: ${s.reasons.join('; ')}`);
    L.push('');
  }
  L.push('## Key levels (4H)');
  L.push('');
  for (const [sym, S] of Object.entries(snap.symbols)) {
    const lv = S.tf['4h'].levels;
    L.push(`- **${sym}**: resistance ${lv.resistance.slice(0, 3).map((x) => px(sym, x.price)).join(', ') || '—'} · support ${lv.support.slice(0, 3).map((x) => px(sym, x.price)).join(', ') || '—'} · POC ${px(sym, S.tf['4h'].volumeProfile.poc)}`);
  }
  L.push('');
  L.push('## What the charts say');
  L.push('');
  for (const [sym, S] of Object.entries(snap.symbols)) L.push(`- **${sym} 4H**: ${S.tf['4h'].ta.notes.slice(0, 3).join(' ')}`);
  L.push('');
  const best = [...snap.strategyStats].filter((x) => x.trades >= 20).sort((a, b) => b.avgR - a.avgR).slice(0, 5);
  if (best.length) {
    L.push('## Best backtested strategies right now');
    L.push('');
    for (const b of best) L.push(`- ${b.name}: ${sgn(b.avgR)}R/trade, ${(b.winRate * 100).toFixed(0)}% win, PF ${b.profitFactor.toFixed(2)} (${b.trades} trades)`);
    L.push('');
  }
  if (DASHBOARD_URL) L.push(`Open the dashboard: ${DASHBOARD_URL}`);
  L.push('');
  L.push('_Generated by tradingterminal. Educational analysis, not financial advice. Size positions so a stop costs at most 1–2% of your account._');
  return { markdown: L.join('\n'), headline: top[0] ? `${top[0].symbol} ${top[0].side} ${top[0].tf} (${top[0].strategyName}, ${top[0].confidence}%)` : 'No new setups', newCount: freshShown.length };
}

// Email-safe HTML version of the markdown report (inline styles, no external CSS).
export function reportHtml(markdown) {
  const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const inline = (s) => esc(s)
    .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
    .replace(/(^|[^\w])_(.+?)_(?!\w)/g, '$1<i style="color:#5a6877">$2</i>')
    .replace(/(https?:\/\/[^\s<)]+)/g, '<a href="$1" style="color:#b86e00">$1</a>')
    .replace(/\bLONG\b/g, '<span style="color:#0e8a5f;font-weight:700">LONG</span>')
    .replace(/\bSHORT\b/g, '<span style="color:#c4363f;font-weight:700">SHORT</span>');
  const td = 'padding:6px 10px;border-bottom:1px solid #d3dae2;font-size:13px;white-space:nowrap';
  let out = '', list = false, tbl = [];
  const endList = () => { if (list) { out += '</ul>'; list = false; } };
  const flush = () => {
    if (!tbl.length) return;
    const rows = tbl.filter((r) => !/^\|\s*-/.test(r)).map((r) => r.replace(/^\||\|$/g, '').split('|').map((c) => c.trim()));
    out += `<div style="overflow-x:auto"><table style="border-collapse:collapse;margin:8px 0">` +
      `<tr>${rows[0].map((c) => `<th style="${td};text-align:left;color:#5a6877;font-size:11px;text-transform:uppercase">${inline(c)}</th>`).join('')}</tr>` +
      rows.slice(1).map((r) => `<tr>${r.map((c) => `<td style="${td}">${inline(c)}</td>`).join('')}</tr>`).join('') + '</table></div>';
    tbl = [];
  };
  for (const l of markdown.split('\n')) {
    if (l.startsWith('|')) { endList(); tbl.push(l); continue; }
    flush();
    if (l.startsWith('# ')) { endList(); out += `<h1 style="font-size:20px;margin:0 0 12px">${inline(l.slice(2))}</h1>`; }
    else if (l.startsWith('## ')) { endList(); out += `<h2 style="font-size:16px;margin:22px 0 8px;padding-top:12px;border-top:1px solid #d3dae2">${inline(l.slice(3))}</h2>`; }
    else if (l.startsWith('### ')) { endList(); out += `<h3 style="font-size:14px;margin:14px 0 4px">${inline(l.slice(4))}</h3>`; }
    else if (l.startsWith('- ')) { if (!list) { out += '<ul style="margin:4px 0;padding-left:20px">'; list = true; } out += `<li style="margin:2px 0;font-size:13px">${inline(l.slice(2))}</li>`; }
    else if (l.trim()) { endList(); out += `<p style="margin:8px 0;font-size:13px">${inline(l)}</p>`; }
    else endList();
  }
  flush(); endList();
  return `<div style="font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;color:#121a23;max-width:720px;line-height:1.45">${out}</div>`;
}
